#!/usr/bin/env node
//
// Natural Earth 110m -> apps/web/src/lib/regions.json
//
//   node scripts/extract-geometry.mjs
//
// Every country in the dataset, simplified enough to ship to a browser. The
// output is committed, so the app has no build-time data step and no runtime
// fetch.
//
// ADM0_A3 is the country code, not ISO_A3: ISO_A3 is "-99" for France and
// Norway, which is how they went missing the first time this ran.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'data/raw/geography/ne_110m_admin_0_countries.geojson');
const target = resolve(root, 'apps/web/src/lib/regions.json');

/** Rings smaller than this are islands the eye cannot resolve at world scale. */
const MIN_RING_POINTS = 5;
/** Keep at most this many rings per country, largest first. */
const MAX_RINGS = 6;
/** Roughly this many points per ring after decimation. */
const TARGET_POINTS = 34;

function decimate(ring) {
  if (ring.length <= TARGET_POINTS) return ring;
  const stride = Math.ceil(ring.length / TARGET_POINTS);
  const out = ring.filter((_, i) => i % stride === 0);
  // Keep the ring closed, or the path fills to the wrong place.
  const first = out[0];
  const last = out[out.length - 1];
  if (first[0] !== last[0] || first[1] !== last[1]) out.push(first);
  return out;
}

const round = (n) => Math.round(n * 100) / 100;

function ringsOf(geometry) {
  const polygons =
    geometry.type === 'Polygon'
      ? [geometry.coordinates]
      : geometry.type === 'MultiPolygon'
        ? geometry.coordinates
        : [];
  // Outer ring only. Holes are invisible at this scale and double the payload.
  return polygons
    .map((polygon) => polygon[0])
    .filter((ring) => Array.isArray(ring) && ring.length >= MIN_RING_POINTS)
    .sort((a, b) => b.length - a.length)
    .slice(0, MAX_RINGS)
    .map((ring) => decimate(ring).map(([lon, lat]) => [round(lon), round(lat)]));
}

const geo = JSON.parse(readFileSync(source, 'utf8'));
const out = {};
let dropped = 0;

for (const feature of geo.features) {
  const props = feature.properties;
  const code = props.ADM0_A3;
  const rings = ringsOf(feature.geometry);
  if (typeof code !== 'string' || code.length !== 3 || rings.length === 0) {
    dropped += 1;
    continue;
  }
  out[code] = {
    name: props.NAME ?? code,
    continent: props.CONTINENT ?? 'Unknown',
    // Natural Earth's own label anchor beats a centroid for countries that are
    // mostly archipelago.
    at: [round(props.LABEL_X ?? 0), round(props.LABEL_Y ?? 0)],
    rings,
  };
}

const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
writeFileSync(target, JSON.stringify(sorted) + '\n');

// The kernel needs the code list but not the shapes, and @genesis/models cannot
// reach into the web app, so the table is generated into the package too.
const table = resolve(root, 'packages/models/src/regions.ts');
const rows = Object.entries(sorted)
  .map(
    ([code, region]) =>
      `  { code: '${code}', name: ${JSON.stringify(region.name)}, continent: ${JSON.stringify(region.continent)} },`,
  )
  .join('\n');

writeFileSync(
  table,
  `// Generated by scripts/extract-geometry.mjs from Natural Earth 110m.
// Do not edit by hand; run the script.
//
// The code is ADM0_A3, not ISO_A3, because ISO_A3 is "-99" for France and
// Norway and they went missing the first time this ran.

export interface RegionInfo {
  readonly code: string;
  readonly name: string;
  readonly continent: string;
}

/** Every country in the dataset, sorted by code. Order is module order. */
export const REGION_TABLE: readonly RegionInfo[] = [
${rows}
];

export const ALL_REGIONS: readonly string[] = REGION_TABLE.map((r) => r.code);
`,
);

const bytes = readFileSync(target).length;
console.log(
  `${Object.keys(sorted).length} countries -> ${target} (${(bytes / 1024).toFixed(0)} KB)` +
    (dropped > 0 ? `, ${dropped} dropped for having no usable ring` : ''),
);
